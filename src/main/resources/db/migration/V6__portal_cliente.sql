-- Portal do cliente: acesso do cliente, solicitações, orçamento, agendamento,
-- anexos, avaliações, notificações e histórico de status.

-- 1. Usuário do portal vinculado a um cliente
ALTER TABLE usuarios
    ADD COLUMN IF NOT EXISTS cliente_id BIGINT;

ALTER TABLE usuarios
    ADD CONSTRAINT fk_usuario_cliente
        FOREIGN KEY (cliente_id) REFERENCES clientes(id) ON DELETE CASCADE;

-- 2. Solicitações abertas pelo cliente ainda não têm técnico/serviço definidos
ALTER TABLE ordens_servico ALTER COLUMN tecnico_id DROP NOT NULL;
ALTER TABLE ordens_servico ALTER COLUMN servico_id DROP NOT NULL;

ALTER TABLE ordens_servico
    ADD COLUMN IF NOT EXISTS descricao_problema       VARCHAR(2000),
    ADD COLUMN IF NOT EXISTS orcamento_valor          DECIMAL(12,2),
    ADD COLUMN IF NOT EXISTS orcamento_descricao      VARCHAR(2000),
    ADD COLUMN IF NOT EXISTS orcamento_enviado_em     TIMESTAMP,
    ADD COLUMN IF NOT EXISTS orcamento_respondido_em  TIMESTAMP,
    ADD COLUMN IF NOT EXISTS orcamento_motivo_recusa  VARCHAR(500),
    ADD COLUMN IF NOT EXISTS data_agendada            TIMESTAMP,
    ADD COLUMN IF NOT EXISTS agendamento_confirmado   BOOLEAN NOT NULL DEFAULT FALSE;

-- 3. Histórico de eventos da ordem (linha do tempo do acompanhamento)
CREATE TABLE IF NOT EXISTS os_historico (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_id   BIGINT       NOT NULL REFERENCES ordens_servico(id) ON DELETE CASCADE,
    tenant_id  BIGINT       NOT NULL REFERENCES tenants(id),
    status     VARCHAR(40)  NOT NULL,
    descricao  VARCHAR(500) NOT NULL,
    autor      VARCHAR(255),
    data       TIMESTAMP    NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_os_historico_ordem ON os_historico(ordem_id);

-- 4. Arquivos anexados à ordem (fotos, documentos, vídeos)
CREATE TABLE IF NOT EXISTS os_anexos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_id      BIGINT       NOT NULL REFERENCES ordens_servico(id) ON DELETE CASCADE,
    tenant_id     BIGINT       NOT NULL REFERENCES tenants(id),
    nome_original VARCHAR(255) NOT NULL,
    content_type  VARCHAR(150) NOT NULL,
    tamanho       BIGINT       NOT NULL,
    caminho       VARCHAR(500) NOT NULL,
    enviado_por   VARCHAR(255),
    data_envio    TIMESTAMP    NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_os_anexos_ordem ON os_anexos(ordem_id);

-- 5. Avaliação do atendimento (uma por ordem)
CREATE TABLE IF NOT EXISTS avaliacoes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_id     BIGINT    NOT NULL UNIQUE REFERENCES ordens_servico(id) ON DELETE CASCADE,
    tenant_id    BIGINT    NOT NULL REFERENCES tenants(id),
    nota_servico INTEGER   NOT NULL CHECK (nota_servico BETWEEN 1 AND 5),
    nota_tecnico INTEGER   CHECK (nota_tecnico BETWEEN 1 AND 5),
    comentario   VARCHAR(1000),
    data         TIMESTAMP NOT NULL
);

-- 6. Notificações internas por usuário
CREATE TABLE IF NOT EXISTS notificacoes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT       NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    tenant_id  BIGINT       NOT NULL REFERENCES tenants(id),
    ordem_id   BIGINT       REFERENCES ordens_servico(id) ON DELETE CASCADE,
    mensagem   VARCHAR(500) NOT NULL,
    lida       BOOLEAN      NOT NULL DEFAULT FALSE,
    data       TIMESTAMP    NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_notificacoes_usuario ON notificacoes(usuario_id, lida);
