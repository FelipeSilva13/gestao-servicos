-- Dias em que a empresa abre a agenda para atendimentos, com a janela de horário.
-- Só nesses dias o cliente (e a equipe) conseguem marcar um atendimento.
CREATE TABLE dias_atendimento (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    data        DATE   NOT NULL,
    hora_inicio TIME   NOT NULL,
    hora_fim    TIME   NOT NULL,
    CONSTRAINT uk_dia_atendimento_tenant_data UNIQUE (tenant_id, data),
    CONSTRAINT ck_dia_atendimento_janela CHECK (hora_inicio < hora_fim)
);

CREATE INDEX idx_ordens_servico_tenant_agenda ON ordens_servico (tenant_id, data_agendada);
